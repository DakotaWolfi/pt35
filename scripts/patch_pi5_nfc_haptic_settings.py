#!/usr/bin/env python3
"""Upgrade the already patched recovered Pi5 NFC GUI with a haptics dialog.

No scanner/driver changes. Refuses unknown source layouts and preserves backups.
"""
import ast
from pathlib import Path

path = Path.home() / "pt35-old-recovery/pt35-nfc-bench/nfc/pt35_nfc_gui.py"
marker = "# PT35_PI5_NFC_HAPTIC_SETTINGS_V2"
if not path.is_file():
    raise SystemExit(f"Recovered NFC GUI not found: {path}")
source = path.read_text(encoding="utf-8")
if marker in source:
    print("NFC vibration settings already installed.")
    raise SystemExit(0)
if "# PT35_PI5_NFC_FEEDBACK_V1" not in source:
    raise SystemExit("Pi5 feedback V1 missing. Run scripts/apply_pi5_nfc_feedback.sh first.")

old_import = "from pi5_nfc_haptics import notify as notify_haptic, new_scan as reset_haptic"
new_import = (
    "from pi5_nfc_haptics import new_scan as reset_haptic\n"
    "from pi5_nfc_haptic_settings import open_settings as open_haptic_settings\n"
    + marker
)
old_controls = (
    "        enabled = self.draft['haptic_enabled']\n"
    "        Button(body, f\"New tag vibration   {'ON' if enabled else 'OFF'}\",\n"
    "               lambda: self.change('haptic_enabled', not enabled), selected=enabled, anchor='w').pack(fill='x', pady=3)\n"
    "        self.options(body, 'Vibration pattern', 'haptic_effect',\n"
    "                     {'1': 'Strong click', '10': 'Sharp click', '47': 'Soft pulse'})\n"
)
new_controls = (
    "        Button(body, 'Configure NFC vibrations',\n"
    "               lambda: open_haptic_settings(self), anchor='w').pack(fill='x', pady=4)\n"
)
old_notify = (
    "            if not self.stopping:\n"
    "                notify_haptic(self.newest.get('uid'), self.settings.get('haptic_enabled', False),\n"
    "                              self.settings.get('haptic_effect', '47'))\n"
)

for name, old in (("haptic import", old_import),
                  ("settings controls", old_controls),
                  ("obsolete tag cue", old_notify)):
    count = source.count(old)
    if count != 1:
        raise SystemExit(
            f"Expected exactly one {name} anchor, found {count}; "
            "no file changed. Inspect recovered GUI version."
        )

result = source.replace(old_import, new_import)
result = result.replace(old_controls, new_controls)
# Tag haptic is generated by the Pi5 feedback adapter; do not duplicate it.
result = result.replace(old_notify, "")
ast.parse(result, filename=str(path))
backup = path.with_name(path.name + ".pre-haptic-settings-v2.bak")
if backup.exists():
    raise SystemExit(f"Backup already present: {backup}. No changes made.")
backup.write_text(source, encoding="utf-8")
path.write_text(result, encoding="utf-8")
print(f"Added NFC vibration settings button: {path}")
print(f"Backup: {backup}")
